package repository

import (
	"context"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
)

// repositoryDB is implemented by both pgxpool.Pool and pgx.Tx. Accepting the
// interface lets repository operations participate in a caller-owned
// transaction, which is useful for atomic workflows and rollback-scoped tests.
type repositoryDB interface {
	Begin(context.Context) (pgx.Tx, error)
	Exec(context.Context, string, ...any) (pgconn.CommandTag, error)
	Query(context.Context, string, ...any) (pgx.Rows, error)
	QueryRow(context.Context, string, ...any) pgx.Row
}
