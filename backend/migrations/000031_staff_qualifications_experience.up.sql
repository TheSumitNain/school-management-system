-- V31: school-scoped staff education, certification and employment history.
-- The staff profile composite FK is the tenant boundary for every record.

CREATE TABLE public.staff_qualifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL,
    staff_principal_id BIGINT NOT NULL,
    qualification_level VARCHAR(24) NOT NULL
        CHECK (qualification_level IN ('secondary','higher_secondary','diploma','bachelors','masters','doctorate','other')),
    qualification_name VARCHAR(160) NOT NULL
        CHECK (length(btrim(qualification_name)) BETWEEN 1 AND 160),
    specialization VARCHAR(160),
    institution_name VARCHAR(200),
    board_or_university VARCHAR(200),
    completion_year SMALLINT
        CHECK (completion_year IS NULL OR completion_year BETWEEN 1900 AND 2100),
    score_value NUMERIC(8,3)
        CHECK (score_value IS NULL OR score_value >= 0),
    score_scale VARCHAR(12)
        CHECK (score_scale IS NULL OR score_scale IN ('percent','cgpa','grade','other')),
    credential_reference VARCHAR(100),
    verification_status VARCHAR(12) NOT NULL DEFAULT 'pending'
        CHECK (verification_status IN ('pending','verified','rejected')),
    verification_notes VARCHAR(1000),
    verified_by_principal_id BIGINT,
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT staff_qualifications_profile_school_fkey
        FOREIGN KEY (staff_principal_id, school_id)
        REFERENCES public.staff_profiles (principal_id, school_id) ON DELETE RESTRICT,
    CONSTRAINT staff_qualifications_score_pair_check
        CHECK ((score_value IS NULL AND score_scale IS NULL) OR (score_value IS NOT NULL AND score_scale IS NOT NULL)),
    CONSTRAINT staff_qualifications_verifier_pair_check
        CHECK ((verification_status = 'pending' AND verified_by_principal_id IS NULL AND verified_at IS NULL)
            OR (verification_status IN ('verified','rejected') AND verified_by_principal_id IS NOT NULL AND verified_at IS NOT NULL))
);

CREATE INDEX ix_staff_qualifications_school_staff
    ON public.staff_qualifications (school_id, staff_principal_id, created_at DESC);

CREATE TABLE public.staff_certifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL,
    staff_principal_id BIGINT NOT NULL,
    certificate_name VARCHAR(160) NOT NULL
        CHECK (length(btrim(certificate_name)) BETWEEN 1 AND 160),
    issuing_organization VARCHAR(200),
    issue_date DATE,
    expiry_date DATE,
    credential_id VARCHAR(100),
    verification_status VARCHAR(12) NOT NULL DEFAULT 'pending'
        CHECK (verification_status IN ('pending','verified','rejected')),
    verification_notes VARCHAR(1000),
    verified_by_principal_id BIGINT,
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT staff_certifications_profile_school_fkey
        FOREIGN KEY (staff_principal_id, school_id)
        REFERENCES public.staff_profiles (principal_id, school_id) ON DELETE RESTRICT,
    CONSTRAINT staff_certifications_dates_check
        CHECK (issue_date IS NULL OR expiry_date IS NULL OR expiry_date >= issue_date),
    CONSTRAINT staff_certifications_verifier_pair_check
        CHECK ((verification_status = 'pending' AND verified_by_principal_id IS NULL AND verified_at IS NULL)
            OR (verification_status IN ('verified','rejected') AND verified_by_principal_id IS NOT NULL AND verified_at IS NOT NULL))
);

CREATE INDEX ix_staff_certifications_school_staff
    ON public.staff_certifications (school_id, staff_principal_id, created_at DESC);

CREATE TABLE public.staff_experience (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id BIGINT NOT NULL,
    staff_principal_id BIGINT NOT NULL,
    employer_name VARCHAR(200) NOT NULL
        CHECK (length(btrim(employer_name)) BETWEEN 1 AND 200),
    designation VARCHAR(120) NOT NULL
        CHECK (length(btrim(designation)) BETWEEN 1 AND 120),
    employment_type VARCHAR(20)
        CHECK (employment_type IS NULL OR employment_type IN ('full_time','part_time','contract','internship','volunteer','other')),
    start_date DATE NOT NULL,
    end_date DATE,
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    description VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT staff_experience_profile_school_fkey
        FOREIGN KEY (staff_principal_id, school_id)
        REFERENCES public.staff_profiles (principal_id, school_id) ON DELETE RESTRICT,
    CONSTRAINT staff_experience_dates_check
        CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT staff_experience_current_check
        CHECK ((is_current = TRUE AND end_date IS NULL) OR (is_current = FALSE))
);

CREATE INDEX ix_staff_experience_school_staff
    ON public.staff_experience (school_id, staff_principal_id, start_date DESC);

