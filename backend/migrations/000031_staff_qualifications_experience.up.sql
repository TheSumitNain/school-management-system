-- System-role permission bundles are immutable at runtime. This migration is
-- the controlled seed point for the new staff profile permissions.
ALTER TABLE public.role_permissions DISABLE TRIGGER trg_protect_system_role_permissions;
INSERT INTO public.role_permissions (role_id, permission_id)
SELECT r.id, p.id
  FROM public.roles r
  CROSS JOIN public.permissions p
 WHERE r.principal_type = 'staff'
   AND r.scope_type = 'school'
   AND r.role_key = 'school_admin'
   AND r.is_system = TRUE
   AND r.school_id IS NOT NULL
   AND p.permission_key IN ('staff.qualifications.read','staff.qualifications.manage','staff.qualifications.verify')
   AND p.scope_type = 'school'
   AND p.is_active = TRUE;
ALTER TABLE public.role_permissions ENABLE TRIGGER trg_protect_system_role_permissions;
